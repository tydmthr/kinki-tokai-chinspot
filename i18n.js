let CURRENT_LANG = (() => {
  const url = new URLSearchParams(location.search);
  if (url.get('lang') === 'en') return 'en';
  if (url.get('lang') === 'ja') return 'ja';
  const stored = localStorage.getItem('bizjp_lang');
  if (stored === 'en' || stored === 'ja') return stored;
  // ブラウザ言語から推定
  return (navigator.language || 'ja').toLowerCase().startsWith('ja') ? 'ja' : 'en';
})();

function t(key) { return I18N[CURRENT_LANG][key] || I18N.ja[key] || key; }

function applyI18n() {
  document.documentElement.lang = CURRENT_LANG === 'en' ? 'en' : 'ja';
  document.body.dataset.lang = CURRENT_LANG;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    el.innerHTML = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = t(key);
  });
  // ラベル切替
  const langLabel = document.getElementById('langLabel');
  if (langLabel) langLabel.textContent = CURRENT_LANG === 'ja' ? 'EN' : 'JA';
  // タイトル切替
  document.title = CURRENT_LANG === 'en'
    ? 'Bizarre Japan — 50 Strange Spots & 47 Wild Festivals of Kinki & Tokai'
    : '異界巡礼 — 近畿・東海 珍スポット50＆奇祭47百景 | Bizarre Japan';
}

function setLang(lang) {
  CURRENT_LANG = lang;
  localStorage.setItem('bizjp_lang', lang);
  applyI18n();
  // 再描画フック
  if (window.refreshAll) window.refreshAll();
}

// データから言語版テキストを取り出すヘルパー
function pick(obj, jaField, enField) {
  if (CURRENT_LANG === 'en' && obj[enField]) return obj[enField];
  return obj[jaField] || '';
}
function pickArr(obj, jaField, enField) {
  if (CURRENT_LANG === 'en' && obj[enField] && obj[enField].length) return obj[enField];
  return obj[jaField] || [];
}
function catLabel(cat) {
  const map = { bkyu: 'm.cat.bkyu', folk: 'm.cat.folk', horror: 'm.cat.horror', mystery: 'm.cat.mystery' };
  return t(map[cat] || cat);
}
function fcatLabel(cat) {
  const ja = { naked: '裸祭', fire: '火祭', weird: '奇習', sex: '性祭', animal: '動物', other: 'その他' };
  const en = { naked: 'Naked', fire: 'Fire', weird: 'Weird', sex: 'Fertility', animal: 'Animal', other: 'Other' };
  return CURRENT_LANG === 'en' ? (en[cat] || cat) : (ja[cat] || cat);
}
